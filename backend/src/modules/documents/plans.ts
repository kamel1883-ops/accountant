// اشتراك المنصة غير خاضع لضريبة القيمة المضافة: المبلغ بعد الخصم هو المستحق كاملاً.
export function priceBreakdown(price: number, discount = 0) {
  const r = (n: number) => Math.round(n * 100) / 100;
  const net = r(Math.max(0, price - discount));
  return { base: price, discount, net, vat: 0, total: net };
}

export function usersText(n: number) {
  return n === 1 ? 'مستخدم واحد' : `حتى ${n} مستخدمين`;
}
