export function localizeNote(text: unknown, lang: Lang) {
  const s = typeof text === 'string' ? text : text == null ? '' : String(text);
  if (!s || lang !== 'en') return s;
  let v = s;
  for (const [ar, en] of NOTES) if (v.includes(ar)) v = v.split(ar).join(en);
  return v;
}

/** كل التواريخ في النظام والتقارير ميلادية (yyyy-mm-dd) بغض النظر عن لغة الواجهة */
export const gdate = (d: unknown) => {
  if (d == null || d === '') return '—';
  try {
    const x = new Date(d as string | Date);
    return isNaN(x.getTime()) ? '—' : x.toISOString().slice(0, 10);
  } catch {
    return '—';
  }
};

/** الأرقام دائماً بالأرقام اللاتينية لتطابق المستندات المطبوعة */
export const money = (n: unknown) => {
  const x = typeof n === 'number' ? n : Number(n);
  if (!Number.isFinite(x)) return '0.00';
  try {
    return x.toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 });
  } catch {
    return x.toFixed(2);
  }
};

